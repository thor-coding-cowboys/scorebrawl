#!/usr/bin/env bun
/**
 * `bun dev`: starts the local `emulate` providers (GitHub/Google OAuth, Resend)
 * next to the app and points the worker at them.
 *
 * Worker bindings come from wrangler dotenv, which outranks the parent shell, so
 * the values are written to the gitignored `apps/worker/.env.local` on first run.
 * Run `EMULATE=0 bun dev` to talk to the real providers instead.
 */

import { existsSync } from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dir, "..");
const emulateBin = path.join(root, "node_modules", ".bin", "emulate");
const workerEnvFile = path.join(root, "apps", "worker", ".env.local");
const discoveryUrl = "http://localhost:4002/.well-known/openid-configuration";

const emulateEnabled = !["0", "false", "off"].includes((process.env.EMULATE ?? "").toLowerCase());

const emulatedEnv = `# Generated by \`bun dev\` (scripts/dev.ts) for the local \`emulate\` providers.
# Delete this file, or run \`EMULATE=0 bun dev\`, to use the real GitHub/Google/Resend.
# Secrets must match the seeded OAuth apps in emulate.config.yaml.
# Portless strips the :1355 port from the Host header, so pin the auth base URL
# or OAuth callbacks point at a URL the browser cannot reach.
BETTER_AUTH_URL=https://scorebrawl.localhost:1355
EMULATE_GITHUB_URL=http://localhost:4001
EMULATE_GOOGLE_URL=http://localhost:4002
GITHUB_CLIENT_SECRET=emulate-github-secret
GOOGLE_CLIENT_SECRET=emulate-google-secret
RESEND_API_KEY=re_emulated_key
RESEND_BASE_URL=http://localhost:4008
`;

async function emulatorReady(timeoutMs: number) {
	try {
		const response = await fetch(discoveryUrl, { signal: AbortSignal.timeout(timeoutMs) });
		return response.ok;
	} catch {
		return false;
	}
}

let emulator: Bun.Subprocess | undefined;

const childEnv: Record<string, string | undefined> = { ...process.env };

if (emulateEnabled) {
	// The web app only renders the social buttons when these are set; vite reads
	// them from the process environment, which turbo passes through.
	childEnv.VITE_GITHUB_CLIENT_ID ??= "Ov23liEHPLUdBgTj5Cxu";
	childEnv.VITE_GOOGLE_CLIENT_ID ??=
		"972190779505-ob8vi6970ib3c8i46plgmu4i9cpr7ohg.apps.googleusercontent.com";

	await Bun.write(workerEnvFile, emulatedEnv);
	console.log("emulate: wrote apps/worker/.env.local (gitignored)");

	if (!(await emulatorReady(300))) {
		if (!existsSync(emulateBin)) {
			console.error(`Missing ${emulateBin}. Run \`bun install\` first.`);
			process.exit(1);
		}

		console.log("emulate: starting GitHub/Google/Resend emulators on :4001/:4002/:4008");
		emulator = Bun.spawn(
			[emulateBin, "start", "--seed", "emulate.config.yaml", "--service", "github,google,resend"],
			{ cwd: root, stdout: "inherit", stderr: "inherit" }
		);

		const deadline = Date.now() + 20_000;
		while (Date.now() < deadline) {
			if (await emulatorReady(500)) break;
			await Bun.sleep(250);
		}

		if (!(await emulatorReady(500))) {
			// Another process (e.g. Playwright's webServer) may own the ports.
			console.warn("emulate: discovery endpoint is not responding; continuing without it");
		}
	}
}

const app = Bun.spawn(["bun", "run", "dev:app"], {
	cwd: root,
	env: childEnv,
	stdin: "inherit",
	stdout: "inherit",
	stderr: "inherit",
});

function shutdown() {
	app.kill();
	emulator?.kill();
	process.exit(0);
}

process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);

const code = await app.exited;
emulator?.kill();
process.exit(code);
